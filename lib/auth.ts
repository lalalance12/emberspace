import "server-only";

import { betterAuth } from "better-auth";
import { nextCookies } from "better-auth/next-js";

import { pool } from "@/lib/db";
import { siteURL } from "@/lib/site-url";

/**
 * Accounts and sessions. Email and password, nothing else — the same shape the
 * Supabase version had after the magic link was removed, and for the same
 * reason: nothing here sends email, so nothing here can be rate limited into
 * uselessness. There is no self-serve password recovery; a forgotten password
 * is reset by whoever runs the database.
 *
 * Better Auth owns four tables (auth_user, auth_session, auth_account,
 * auth_verification), created in db/migrations/20260805085900_postgres_compat.sql.
 * A new auth_user row fires handle_new_user(), which creates the profile —
 * the app never inserts one itself.
 *
 * BETTER_AUTH_SECRET signs the session cookie. It is server-only and must be
 * set in every environment; `openssl rand -base64 32` makes one.
 */
export const auth = betterAuth({
  database: pool,
  secret: process.env.BETTER_AUTH_SECRET,
  baseURL: {
    // Previews get their own *.vercel.app host on every deploy; the session
    // cookie and the auth routes have to work on whichever one is open.
    allowedHosts: ["localhost:*", "127.0.0.1:*", "*.vercel.app", new URL(siteURL()).host],
    fallback: siteURL(),
  },
  emailAndPassword: {
    enabled: true,
    minPasswordLength: 8,
    // Signup lands straight on /onboarding, signed in. No confirmation step.
    autoSignIn: true,
  },
  user: { modelName: "auth_user" },
  session: { modelName: "auth_session" },
  account: { modelName: "auth_account" },
  verification: { modelName: "auth_verification" },
  advanced: {
    // uuids, generated by Postgres, so profiles.id can reference auth_user.id.
    database: { generateId: "uuid" },
  },
  // Lets server actions set the session cookie (sign in, sign out).
  plugins: [nextCookies()],
});
